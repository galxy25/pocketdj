package com.levi.pocketdj.data.games.inthepocket

import com.levi.pocketdj.data.PdjJson
import com.levi.pocketdj.data.pockets.ListeningContextTag
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.double
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The on-device round-learning twin of analyze.mjs `learnFromRounds`. The expected table in
 * fixtures/learning_rounds_expected.json was GENERATED by running the lambda's own
 * `learnFromRounds` over the same 8 rounds (see the JS test of the same name).
 */
class InThePocketLearningTest {
    private val placeA = "plc_0f1e2d3c4b5a6978"
    private val funk = listOf(InThePocketTarget("genre", "funk", "Funk", 1.0), InThePocketTarget("artist", "ada", "Ada", 1.0))
    private val rock = listOf(InThePocketTarget("genre", "rock", "Rock", 1.0))

    private fun mk(outcome: InThePocketOutcome, targets: List<InThePocketTarget>, place: Boolean = true) =
        TestRounds.round(
            listOf("a", "b", "c", "d"), outcome, targets,
            InThePocketContext("evening", "weekday", 2, if (place) ListeningContextTag.place(placeA) else null),
        )

    private val rounds = listOf(
        mk(InThePocketOutcome.Pocket, funk), mk(InThePocketOutcome.Pocket, funk), mk(InThePocketOutcome.Pocket, funk),
        mk(InThePocketOutcome.Broke(1), rock), mk(InThePocketOutcome.Broke(2), rock),
        mk(InThePocketOutcome.Broke(4), funk), mk(InThePocketOutcome.Abandoned, rock),
        mk(InThePocketOutcome.Pocket, funk, place = false),
    )

    @Test fun multiplierTableMatchesAnalyzeMjs() {
        // (pos, neg) -> multiplier, computed with roundMultiplier in analyze.mjs.
        val table = listOf(
            Triple(0, 0, 1.0), Triple(3, 0, 1.6), Triple(0, 3, 0.4), Triple(1, 0, 1.333), Triple(0, 1, 0.667),
            Triple(2, 1, 1.2), Triple(4, 0, 1.667), Triple(0, 1000, 0.25), Triple(1000, 0, 1.998), Triple(9, 1, 1.667),
        )
        for ((p, n, m) in table) assertEquals("pos=$p neg=$n", m, InThePocketLearning.multiplier(p, n), 0.0)
    }

    @Test fun labelsArePositiveForPocketNegativeForEarlyBreakNeutralOtherwise() {
        val l = rounds.map(InThePocketLearning::label)
        assertEquals(listOf(1, 1, 1, -1, -1, 0, 0, 1), l)
        assertEquals(0, InThePocketLearning.label(mk(InThePocketOutcome.Broke(3), rock)))
        assertEquals(0, InThePocketLearning.label(TestRounds.round(listOf("a"), null)))
    }

    @Test fun contextsMatchTheLambdaFixtureForTheSameRounds() {
        val text = javaClass.classLoader!!.getResource("fixtures/learning_rounds_expected.json")!!.readText()
        val expected = PdjJson.lenient.parseToJsonElement(text).jsonObject["contexts"]!!.jsonArray
        val got = InThePocketLearning.contexts(rounds)
        assertEquals("same context keys", expected.map { it.jsonObject["key"]!!.jsonPrimitive.content }.toSet(), got.keys)
        for (c in expected) {
            val o: JsonObject = c.jsonObject
            val weights = got[o["key"]!!.jsonPrimitive.content]!!
            val ew = o["weights"]!!.jsonArray
            assertEquals(ew.size, weights.size)
            for (w in ew) {
                val wo = w.jsonObject
                val mine = weights[InThePocketLearning.targetKey(wo["dim"]!!.jsonPrimitive.content, wo["value"]!!.jsonPrimitive.content)]
                assertNotNull("$wo", mine)
                assertEquals(wo["pos"]!!.jsonPrimitive.int, mine!!.pos)
                assertEquals(wo["neg"]!!.jsonPrimitive.int, mine.neg)
                assertEquals(wo["multiplier"]!!.jsonPrimitive.double, mine.multiplier, 0.0)
            }
        }
    }

    @Test fun noPlaceRoundCreditsOnlyTheRelaxedKey() {
        val got = InThePocketLearning.contexts(rounds)
        assertEquals(setOf("weekday|evening|*", "weekday|evening|place:$placeA"), got.keys)
        assertEquals(4, got["weekday|evening|*"]!![InThePocketLearning.targetKey("genre", "funk")]!!.pos)
        assertEquals(3, got["weekday|evening|place:$placeA"]!![InThePocketLearning.targetKey("genre", "funk")]!!.pos)
    }

    @Test fun duplicateTargetsInOneRoundCountOnce() {
        val dup = mk(InThePocketOutcome.Pocket, funk + funk)
        val w = InThePocketLearning.contexts(listOf(dup))["weekday|evening|*"]!![InThePocketLearning.targetKey("genre", "funk")]!!
        assertEquals(1, w.pos)
    }

    @Test fun deterministicRegardlessOfRoundOrder() {
        assertEquals(InThePocketLearning.contexts(rounds), InThePocketLearning.contexts(rounds.reversed()))
    }

    @Test fun addRuleIsAtLeast125OnTwoPositives() {
        // 2 positives, 0 negatives => 2*(3)/(4) = 1.5 >= 1.25 (added); 1 positive => 1.333 but pos < 2.
        val two = InThePocketLearning.contexts(listOf(mk(InThePocketOutcome.Pocket, rock), mk(InThePocketOutcome.Pocket, rock)))
        val w = two["weekday|evening|*"]!![InThePocketLearning.targetKey("genre", "rock")]!!
        assertTrue(w.multiplier >= InThePocketScorer.LEARNING_ADD_MIN && w.pos >= 2)
        val one = InThePocketLearning.contexts(listOf(mk(InThePocketOutcome.Pocket, rock)))["weekday|evening|*"]!![InThePocketLearning.targetKey("genre", "rock")]!!
        assertTrue(one.multiplier >= InThePocketScorer.LEARNING_ADD_MIN && one.pos < 2)
    }
}
