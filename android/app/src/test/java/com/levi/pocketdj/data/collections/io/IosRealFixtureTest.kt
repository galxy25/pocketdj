package com.levi.pocketdj.data.collections.io

import com.levi.pocketdj.data.backup.BackupZip
import com.levi.pocketdj.data.collections.CollectionsStore
import com.levi.pocketdj.data.collections.PlaylistNode
import com.levi.pocketdj.data.collections.TrackSource
import java.io.File
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

/**
 * ANS-SVC-2: bytes written by the REAL iOS exporters (BackupZip / PocketZip / PlaylistZip),
 * regenerated by `apple/scripts/export-android-fixtures.sh` from a synthetic store
 * (see ios-real/README.md). Ids are random per generation, so assertions key on names.
 */
class IosRealFixtureTest {
    @get:Rule val tmp = TemporaryFolder()

    private fun res(n: String) = IoTestSupport.resource("backup/ios-real/$n")
    private fun store() = CollectionsStore(file = File(tmp.newFolder(), CollectionsStore.FILE_NAME), now = { 1_790_000_000_000.0 })
    private fun text(b: ByteArray) = String(b, Charsets.UTF_8)

    @Test
    fun backup_decodesFullModel() {
        val bytes = res("backup.pocketdj.zip")
        val (p, skipped) = BackupZip.import(bytes)
        assertEquals(0, skipped.items); assertEquals(0, skipped.art)

        val warm = p.pockets.single { it.name == "Warmups" }
        val chill = p.pockets.single { it.name == "Chill" }
        assertEquals(listOf(chill.id), warm.childPocketIds)                    // nested pockets
        assertEquals(listOf("sng_1", "sng_2"), warm.songIds)
        assertEquals(listOf("alb_2"), warm.albumIds)
        assertEquals(mapOf("sng_1" to 3), warm.songRepeats)
        assertEquals(listOf("Open with the horns"), warm.notes.map { it.text })
        assertEquals(true, warm.cleanOnly); assertEquals(false, warm.recsEnabled)
        assertEquals("pull", warm.amSyncDirection)
        assertNull(chill.cleanOnly); assertNull(chill.recsEnabled)             // unset stays unset

        val folder = p.folders.single { it.name == "Gigs" }
        assertEquals(folder.id, warm.folderId)

        val pl = p.playlists.single()
        assertEquals("Night Set", pl.name)
        assertEquals(listOf("Default", "Peak"), pl.sequences.map { it.name })   // multi-chapter
        val def = pl.sequences[0].children!!; val peak = pl.sequences[1].children!!
        assertEquals(listOf(PlaylistNode.Kind.SONG, PlaylistNode.Kind.SONG, PlaylistNode.Kind.POCKET, PlaylistNode.Kind.ALBUM), def.map { it.kind })
        assertEquals(warm.id, def[2].pocketId)
        assertEquals(2, peak[0].repeatCount)
        assertEquals("Lights down", peak[1].text)
        assertEquals(true, pl.cleanOnly); assertEquals(false, pl.recsEnabled); assertEquals("push", pl.amSyncDirection)
        assertEquals(folder.id, pl.folderId)

        val sl = p.setlists.single()
        assertEquals(pl.id, sl.playlistId); assertEquals("fixture-seed", sl.seed)
        assertEquals(6, sl.tracks.size)
        assertEquals(TrackSource.POCKET, sl.tracks[1].source); assertEquals(warm.id, sl.tracks[1].pocketId)
        assertEquals(true, sl.tracks.last().isText)

        assertEquals("Fixture Crate", com.levi.pocketdj.data.backup.BackupSources.fromWire(p.sourcesJson).single().name)
    }

    @Test
    fun backup_favoritesAndEditsBytesCarried() {
        val (p, _) = BackupZip.import(res("backup.pocketdj.zip"))
        val fav = IoTestSupport.json(p.favoritesData!!) as JsonObject
        val entries = fav["entries"].toString()
        assertTrue(entries.contains("\"sng_1\"") && entries.contains("\"111\""))
        assertTrue("tombstone present", entries.contains("\"sng_3\"") && entries.contains("false"))
        val edits = text(p.editsData!!)
        assertTrue(edits.contains("\"Fixture\"") && edits.contains("Neon (Edit)") && edits.contains("101"))
    }

    @Test
    fun amPlaylistIdNeverTravels_allThreeFiles() {
        for (n in listOf("backup.pocketdj.zip", "pocket.pdjcollection", "playlist.pdjcollection")) {
            val entries = ZipIo.read(res(n))!!
            entries.forEach { (name, b) ->
                assertFalse("$n/$name leaks amPlaylistId", text(b).contains("amPlaylistId"))
                assertFalse("$n/$name leaks AM id", text(b).contains("FIXTURE_AM"))
            }
        }
    }

    @Test
    fun backup_manifestShape() {
        val man = IoTestSupport.json(ZipIo.read(res("backup.pocketdj.zip"))!!["manifest.json"]!!) as JsonObject
        assertEquals("backup", (man["kind"] as JsonPrimitive).content)
        assertEquals("2", (man["schemaVersion"] as JsonPrimitive).content)
        val c = man["counts"] as JsonObject
        assertEquals("2", (c["pockets"] as JsonPrimitive).content)
        assertEquals("1", (c["playlists"] as JsonPrimitive).content)
        assertEquals("1", (c["setlists"] as JsonPrimitive).content)
    }

    @Test
    fun pocketFile_portableWithChildAndItems() {
        val b = PocketZip.read(res("pocket.pdjcollection"))
        assertEquals("Warmups", b.pocket.name)
        assertEquals(listOf("Chill"), b.children.map { it.name })
        assertEquals(listOf(b.children.single().id), b.pocket.childPocketIds)
        assertEquals(true, b.pocket.cleanOnly); assertEquals(false, b.pocket.recsEnabled)
        assertEquals(mapOf("sng_1" to 3), b.pocket.songRepeats)
        // portable: items.json carries songs for sng_1/2/3/5 and alb_2's track songs
        val songIds = b.items.songs.map { it.id }.toSet()
        assertTrue(songIds.containsAll(setOf("sng_1", "sng_2", "sng_3", "sng_5")))
        assertTrue(b.items.albums.any { it.id == "alb_2" })
        assertEquals("Neon", b.items.songs.single { it.id == "sng_1" }.name)
    }

    @Test
    fun playlistFile_portableMultiChapter() {
        val b = PlaylistZip.read(res("playlist.pdjcollection"))
        assertEquals("Night Set", b.playlist.name)
        assertEquals(2, b.playlist.sequences.size)
        assertEquals(setOf("Warmups", "Chill"), b.pockets.map { it.name }.toSet())    // DAG-expanded
        assertEquals(true, b.playlist.cleanOnly)
        assertFalse(b.items.isEmpty)
        assertTrue(b.items.albums.any { it.id == "alb_3" })
    }

    @Test
    fun importAny_allThreeIntoStore_andReimportIsNoop() {
        val s = store()
        for (n in listOf("backup.pocketdj.zip", "pocket.pdjcollection", "playlist.pdjcollection")) s.importAny(res(n))
        val warm = s.pockets.single { it.name == "Warmups" }
        assertNotNull(s.pockets.firstOrNull { it.name == "Chill" })
        assertEquals(1, s.playlists.size)
        assertEquals(1, s.folders.size)
        assertEquals(1, s.setlists.size)
        assertEquals(true, warm.cleanOnly)
        assertNull("no AM binding materializes from exports", warm.amPlaylistId)
        assertNull(s.playlists.single().amPlaylistId)
        val before = listOf(s.pockets, s.playlists, s.setlists, s.folders)
        for (n in listOf("backup.pocketdj.zip", "pocket.pdjcollection", "playlist.pdjcollection")) s.importAny(res(n))
        assertEquals(before, listOf(s.pockets, s.playlists, s.setlists, s.folders))
    }

    @Test
    fun standalonePocketFile_intoFreshStore() {
        val s = store()
        var sink: PortableItems.Payload? = null
        s.onPortableItems = { sink = it }
        s.importAny(res("pocket.pdjcollection"))
        val warm = s.pockets.single { it.name == "Warmups" }
        val chill = s.pockets.single { it.name == "Chill" }
        assertNull(warm.folderId); assertNull(chill.folderId)
        assertEquals(listOf(chill.id), warm.childPocketIds)
        assertTrue(s.playlists.isEmpty())
        val p = sink!!
        assertTrue(p.songs.map { it.id }.containsAll(listOf("sng_1", "sng_2", "sng_3", "sng_5")))
        assertTrue(p.albums.any { it.id == "alb_2" })
    }

    @Test
    fun standalonePlaylistFile_intoFreshStore() {
        val s = store()
        var sink: PortableItems.Payload? = null
        s.onPortableItems = { sink = it }
        s.importAny(res("playlist.pdjcollection"))
        val pl = s.playlists.single { it.name == "Night Set" }
        assertNull(pl.folderId)
        val warm = s.pockets.single { it.name == "Warmups" }
        assertNotNull(s.pockets.firstOrNull { it.name == "Chill" })
        assertNull(warm.folderId)
        val refs = pl.sequences.flatMap { it.children.orEmpty() }.mapNotNull { it.pocketId }
        assertTrue(warm.id in refs)
        val p = sink!!
        assertTrue(p.songs.map { it.id }.containsAll(listOf("sng_1", "sng_2", "sng_3", "sng_5")))
        assertTrue(p.albums.map { it.id }.containsAll(listOf("alb_2", "alb_3")))
    }
}
